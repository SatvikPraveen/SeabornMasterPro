def generate_all(
    out_dir: PathType | None = None, *, seed: int = 0, manifest: bool = True, verbose: bool = True
) -> dict[str, Path]:
    """Regenerate every dataset into ``out_dir`` and write ``MANIFEST.json``.

    Returns
    -------
    dict
        Mapping of dataset name to written CSV path.
    """
    out = Path(out_dir) if out_dir else default_dir()
    out.mkdir(parents=True, exist_ok=True)
    frames = _legacy(seed)
    frames.update({name: fn() for name, fn in _RESEARCH.items()})
    paths: dict[str, Path] = {}
    for name, df in frames.items():
        path = out / REGISTRY[name].filename
        df.to_csv(path, index=False)
        paths[name] = path
        if verbose:
            print(f"✅ {path.name}: {len(df):,} rows × {df.shape[1]} cols")
    if manifest:
        write_manifest(
            list(paths.values()),
            out / "MANIFEST.json",
            relative_to=out,
            extra={"legacy_seed": seed},
        )
    return paths


def load(name: str, data_dir: PathType | None = None) -> pd.DataFrame:
    """Load a dataset by registry name, parsing date columns."""
    if name not in REGISTRY:
        raise KeyError(f"unknown dataset {name!r}; available: {sorted(REGISTRY)}")
    path = Path(data_dir or default_dir()) / REGISTRY[name].filename
    parse = [c for c, t in REGISTRY[name].columns.items() if t.startswith(("date", "datetime"))]
    return pd.read_csv(path, parse_dates=parse or None)


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: ``smp-datasets [--out DIR] [--seed N] [--list]``."""
    parser = argparse.ArgumentParser(description="Regenerate SeabornMasterPro synthetic datasets.")
    parser.add_argument(
        "--out", type=Path, default=None, help="output directory (default: <repo>/datasets)"
    )
    parser.add_argument("--seed", type=int, default=0, help="seed for the legacy dataset stream")
    parser.add_argument("--list", action="store_true", help="print data cards and exit")
    args = parser.parse_args(argv)
    if args.list:
        for card in REGISTRY.values():
            print(f"{card.name:20s} {card.n_rows:>6,} rows  {card.description}")
            print(f"{'':20s} model: {card.generative_model}")
        return 0
    generate_all(args.out, seed=args.seed)
    return 0


