# Research datasets: independent Generator streams with known ground truth.
# ---------------------------------------------------------------------------
def _clinical_trial(seed: int = 2024, n_per_arm: int = 60) -> pd.DataFrame:
    """Three-arm trial with heteroscedastic outcomes and a known dose-response effect.

    Outcome ~ Normal(mu_arm, sigma_arm) with mu = (50, 53, 58) and sigma = (8, 10, 12),
    so that Placebo-vs-High has Cohen's d ≈ 0.78 and Placebo-vs-Low ≈ 0.33.
    """
    rng = np.random.default_rng(seed)
    arms = {"Placebo": (50, 8), "Low Dose": (53, 10), "High Dose": (58, 12)}
    frames = []
    for arm, (mu, sd) in arms.items():
        age = rng.integers(25, 75, n_per_arm)
        baseline = rng.normal(48, 7, n_per_arm)
        outcome = rng.normal(mu, sd, n_per_arm) + 0.15 * (baseline - 48)
        frames.append(
            pd.DataFrame(
                {
                    "Arm": arm,
                    "Age": age,
                    "Sex": rng.choice(["F", "M"], n_per_arm),
                    "Baseline": baseline.round(1),
                    "Outcome": outcome.round(1),
                    "Site": rng.choice(["Site 1", "Site 2", "Site 3"], n_per_arm),
                }
            )
        )
    return pd.concat(frames, ignore_index=True)


def _sensor_readings(seed: int = 7, n_days: int = 120) -> pd.DataFrame:
    """Hourly sensor series with diurnal cycle, weekly seasonality, trend, and outliers."""
    rng = np.random.default_rng(seed)
    t = pd.date_range("2024-01-01", periods=n_days * 24, freq="h")
    hours = np.arange(t.size)
    diurnal = 4 * np.sin(2 * np.pi * hours / 24 - np.pi / 2)
    weekly = 1.5 * np.sin(2 * np.pi * hours / (24 * 7))
    trend = 0.002 * hours
    frames = []
    for sensor, offset in {"S-01": 20.0, "S-02": 21.5, "S-03": 19.0}.items():
        noise = rng.normal(0, 0.8, t.size)
        temp = offset + diurnal + weekly + trend + noise
        outliers = rng.random(t.size) < 0.004
        temp[outliers] += rng.choice([-1, 1], outliers.sum()) * rng.uniform(6, 10, outliers.sum())
        humidity = np.clip(55 - 1.2 * (temp - offset) + rng.normal(0, 3, t.size), 10, 100)
        frames.append(
            pd.DataFrame(
                {
                    "Timestamp": t,
                    "Sensor": sensor,
                    "Temperature (C)": temp.round(2),
                    "Humidity (%)": humidity.round(1),
                    "Anomaly": outliers,
                }
            )
        )
    return pd.concat(frames, ignore_index=True)


def _gene_expression(seed: int = 11, n_genes: int = 40, n_samples: int = 24) -> pd.DataFrame:
    """Log2 expression matrix with two conditions and two co-regulated gene modules."""
    rng = np.random.default_rng(seed)
    condition = np.array(["Control"] * (n_samples // 2) + ["Treated"] * (n_samples // 2))
    module = np.repeat(["Module A", "Module B", "Background"], [8, 8, n_genes - 16])
    base = rng.normal(8, 1.5, n_genes)
    expr = base[:, None] + rng.normal(0, 0.4, (n_genes, n_samples))
    treated = condition == "Treated"
    expr[np.ix_(module == "Module A", treated)] += 1.8
    expr[np.ix_(module == "Module B", treated)] -= 1.2
    genes = [f"GENE{i:03d}" for i in range(1, n_genes + 1)]
    samples = [f"{c[:1]}{i + 1:02d}" for i, c in enumerate(condition)]
    df = pd.DataFrame(expr.round(3), index=pd.Index(genes, name="Gene"), columns=samples)
    df.insert(0, "Module", module)
    return df.reset_index()


