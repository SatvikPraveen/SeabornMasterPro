__all__ = ["REGISTRY", "DatasetCard", "default_dir", "generate_all", "load", "main"]

_ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class DatasetCard:
    """Minimal data card (Gebru et al., 2021) for a synthetic table."""

    name: str
    filename: str
    description: str
    generative_model: str
    columns: dict[str, str]
    n_rows: int
    seed_note: str


def default_dir() -> Path:
    """Directory holding the CSV files (``<repo>/datasets``)."""
    return _ROOT / "datasets"


# ---------------------------------------------------------------------------
# Legacy datasets: a single shared RandomState stream, in this exact order.
# ---------------------------------------------------------------------------
def _legacy(seed: int = 0) -> dict[str, pd.DataFrame]:
    # The legacy global stream is deliberate: it reproduces the original CSVs bit-for-bit.
    np.random.seed(seed)  # noqa: NPY002
    out: dict[str, pd.DataFrame] = {}

    sales = pd.DataFrame(
        {
            "Region": np.random.choice(["North", "South", "East", "West"], 200),  # noqa: NPY002
            "Product": np.random.choice(["Laptop", "Tablet", "Smartphone", "Monitor"], 200),  # noqa: NPY002
            "Units Sold": np.random.poisson(30, 200),  # noqa: NPY002
            "Unit Price": np.random.uniform(100, 1000, 200).round(2),  # noqa: NPY002
        }
    )
    sales["Total Sales"] = (sales["Units Sold"] * sales["Unit Price"]).round(2)
    out["sales_data"] = sales

    out["employee_data"] = pd.DataFrame(
        {
            "Department": np.random.choice(["HR", "Engineering", "Marketing", "Finance"], 150),  # noqa: NPY002
            "Gender": np.random.choice(["Male", "Female"], 150),  # noqa: NPY002
            "Experience (Years)": np.random.randint(1, 21, 150),  # noqa: NPY002
            "Salary": np.random.normal(70000, 15000, 150).astype(int),  # noqa: NPY002
        }
    )

    study = np.random.uniform(0, 10, 100)  # noqa: NPY002
    sleep = np.random.uniform(4, 9, 100)  # noqa: NPY002
    score = 3.5 * study + 2 * sleep + np.random.normal(0, 3, 100)  # noqa: NPY002
    out["student_scores"] = pd.DataFrame(
        {"Study Hours": study.round(2), "Sleep Hours": sleep.round(2), "Test Score": score.round(2)}
    )

    out["ecommerce_data"] = pd.DataFrame(
        {
            "User ID": np.arange(1000, 1100),
            "Age": np.random.randint(18, 60, 100),  # noqa: NPY002
            "Session Time (min)": np.random.normal(12, 5, 100).round(2),  # noqa: NPY002
            "Page Views": np.random.poisson(6, 100),  # noqa: NPY002
        }
    )

    out["marketing_campaign"] = pd.DataFrame(
        {
            "Campaign": np.random.choice(["A", "B", "C", "D"], 120),  # noqa: NPY002
            "Channel": np.random.choice(["Email", "Social Media", "Ads", "Referral"], 120),  # noqa: NPY002
            "Spend ($)": np.random.uniform(500, 10000, 120).round(2),  # noqa: NPY002
            "ROI (%)": np.random.normal(12, 4, 120).round(2),  # noqa: NPY002
        }
    )

    dates = pd.date_range(start="2024-01-01", end="2024-06-30", freq="D")
    sessions = np.random.poisson(150, len(dates))  # noqa: NPY002
    page_views = sessions * np.random.uniform(1.2, 1.8, len(dates))  # noqa: NPY002
    bounce = np.random.uniform(30, 70, len(dates))  # noqa: NPY002
    out["web_traffic"] = pd.DataFrame(
        {
            "Date": dates,
            "Sessions": sessions,
            "Page Views": page_views.round(0).astype(int),
            "Bounce Rate (%)": bounce.round(2),
        }
    )
    return out


