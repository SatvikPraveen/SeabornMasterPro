"""Deterministic synthetic datasets with data cards.

Every dataset is generated from a documented stochastic model with a fixed
seed, so the CSVs in ``datasets/`` can be regenerated byte-for-byte and verified
against ``datasets/MANIFEST.json``.

The six *legacy* datasets reproduce the exact draws of the original
``scripts/generate_datasets.py`` (a single ``np.random.seed(0)`` stream) so that
figures in the curriculum notebooks remain reproducible. Newer datasets use
independent :class:`numpy.random.Generator` streams.
"""

from __future__ import annotations

import argparse
